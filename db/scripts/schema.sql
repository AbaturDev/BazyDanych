-- ---------------------------------------------------------------------
-- Producent
-- ---------------------------------------------------------------------
CREATE TABLE Producent (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Nazwa                     NVARCHAR2(100) NOT NULL,
    NIP                       CHAR(10),
    Kraj                      NVARCHAR2(50),
    DataZalozenia             DATE,
    CONSTRAINT pk_producent      PRIMARY KEY (ID),
    CONSTRAINT uq_producent_nip  UNIQUE (NIP),
    CONSTRAINT ck_producent_nip  CHECK (REGEXP_LIKE(NIP, '^[0-9]{10}$'))
);

-- ---------------------------------------------------------------------
-- Lek
-- ---------------------------------------------------------------------
CREATE TABLE Lek (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Nazwa            NVARCHAR2(100) NOT NULL,
    KodEAN           CHAR(13),
    CenaDetaliczna   NUMBER(10,2)   NOT NULL,
    DataWprowadzenia DATE,
    ProducentID      NUMBER         NOT NULL,
    OpisLeku         NVARCHAR2(1000),
    CONSTRAINT pk_lek            PRIMARY KEY (ID),
    CONSTRAINT uq_lek_ean        UNIQUE (KodEAN),
    CONSTRAINT ck_lek_ean        CHECK (REGEXP_LIKE(KodEAN, '^[0-9]{13}$')),
    CONSTRAINT ck_lek_cena       CHECK (CenaDetaliczna > 0),
    CONSTRAINT fk_lek_producent  FOREIGN KEY (ProducentID) REFERENCES Producent (ID)
);

-- ---------------------------------------------------------------------
-- Dostawca
-- ---------------------------------------------------------------------
CREATE TABLE Dostawca (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Nazwa               NVARCHAR2(100) NOT NULL,
    NIP                 CHAR(10),
    Telefon             VARCHAR2(20),
    DataPodpisaniaUmowy DATE,
    CONSTRAINT pk_dostawca      PRIMARY KEY (ID),
    CONSTRAINT uq_dostawca_nip  UNIQUE (NIP),
    CONSTRAINT ck_dostawca_nip  CHECK (REGEXP_LIKE(NIP, '^[0-9]{10}$'))
);

-- ---------------------------------------------------------------------
-- Zamowienie
-- ---------------------------------------------------------------------
CREATE TABLE Zamowienie (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DostawcaID        NUMBER        NOT NULL,
    DataZamowienia    DATE          NOT NULL,
    PlanowanaDostawa  DATE,
    Status            NVARCHAR2(20) DEFAULT 'NOWE' NOT NULL,
    WartoscZamowienia NUMBER(12,2)  DEFAULT 0 NOT NULL,
    KodZamowienia     CHAR(10),
    CONSTRAINT pk_zamowienie          PRIMARY KEY (ID),
    CONSTRAINT uq_zamowienie_kod      UNIQUE (KodZamowienia),
    CONSTRAINT ck_zamowienie_status   CHECK (Status IN ('NOWE', 'ZATWIERDZONE', 'W_REALIZACJI',
                                                        'ZREALIZOWANE', 'ANULOWANE')),
    CONSTRAINT ck_zamowienie_wartosc  CHECK (WartoscZamowienia >= 0),
    CONSTRAINT ck_zamowienie_dostawa  CHECK (PlanowanaDostawa IS NULL
                                             OR PlanowanaDostawa >= DataZamowienia),
    CONSTRAINT fk_zamowienie_dostawca FOREIGN KEY (DostawcaID) REFERENCES Dostawca (ID)
);

-- ---------------------------------------------------------------------
-- PozycjaZamowienia
-- ---------------------------------------------------------------------
CREATE TABLE PozycjaZamowienia (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ZamowienieID     NUMBER       NOT NULL,
    LekID            NUMBER       NOT NULL,
    Ilosc            NUMBER(10)   NOT NULL,
    CenaZakupu       NUMBER(10,2) NOT NULL,
    DataDostarczenia DATE,
    KodPozycji       CHAR(8),
    CONSTRAINT pk_pozycjazamowienia     PRIMARY KEY (ID),
    CONSTRAINT ck_pozzam_ilosc          CHECK (Ilosc > 0),
    CONSTRAINT ck_pozzam_cena           CHECK (CenaZakupu > 0),
    CONSTRAINT fk_pozzam_zamowienie     FOREIGN KEY (ZamowienieID) REFERENCES Zamowienie (ID)
                                        ON DELETE CASCADE,
    CONSTRAINT fk_pozzam_lek            FOREIGN KEY (LekID) REFERENCES Lek (ID)
);

-- ---------------------------------------------------------------------
-- Sprzedaz
-- ---------------------------------------------------------------------
CREATE TABLE Sprzedaz (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DataSprzedazy    DATE         NOT NULL,
    NumerParagonu    VARCHAR2(30),
    SposobPlatnosci  VARCHAR2(20),
    WartoscCalkowita NUMBER(12,2) DEFAULT 0 NOT NULL,
    KodKasy          CHAR(4),
    CONSTRAINT pk_sprzedaz          PRIMARY KEY (ID),
    CONSTRAINT uq_sprzedaz_paragon  UNIQUE (NumerParagonu),
    CONSTRAINT ck_sprzedaz_platnosc CHECK (SposobPlatnosci IN ('GOTOWKA', 'KARTA', 'BLIK')),
    CONSTRAINT ck_sprzedaz_wartosc  CHECK (WartoscCalkowita >= 0)
);

-- ---------------------------------------------------------------------
-- PozycjaSprzedazy
-- ---------------------------------------------------------------------
CREATE TABLE PozycjaSprzedazy (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SprzedazID    NUMBER       NOT NULL,
    LekID         NUMBER       NOT NULL,
    Ilosc         NUMBER(10)   NOT NULL,
    CenaSprzedazy NUMBER(10,2) NOT NULL,
    Rabat         NUMBER(5,2)  DEFAULT 0 NOT NULL,
    DataUjecia    DATE         NOT NULL,
    KodPozycji    CHAR(8),
    CONSTRAINT pk_pozycjasprzedazy  PRIMARY KEY (ID),
    CONSTRAINT ck_pozsprz_ilosc     CHECK (Ilosc > 0),
    CONSTRAINT ck_pozsprz_cena      CHECK (CenaSprzedazy > 0),
    CONSTRAINT ck_pozsprz_rabat     CHECK (Rabat BETWEEN 0 AND 100),
    CONSTRAINT fk_pozsprz_sprzedaz  FOREIGN KEY (SprzedazID) REFERENCES Sprzedaz (ID)
                                    ON DELETE CASCADE,
    CONSTRAINT fk_pozsprz_lek       FOREIGN KEY (LekID) REFERENCES Lek (ID)
);
