#!/bin/bash
set -euo pipefail

# Startowe skrypty gvenzl działają po każdym uruchomieniu Oracle, także na
# istniejącym wolumenie. SQL*Loader ładuje CSV partiami, a klucz główny odrzuca
# rekordy, które mogły zostać zapisane przy poprzedniej, przerwanej próbie.
sqlplus -L -s / as sysdba <<'SQL' > /tmp/apteka_counts.log
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;
SET PAGESIZE 0 FEEDBACK OFF VERIFY OFF HEADING OFF ECHO OFF
SELECT COUNT(*) FROM APTEKA.ZAMOWIENIE;
SELECT COUNT(*) FROM APTEKA.POZYCJAZAMOWIENIA;
SELECT COUNT(*) FROM APTEKA.SPRZEDAZ;
SELECT COUNT(*) FROM APTEKA.POZYCJASPRZEDAZY;
EXIT
SQL
mapfile -t liczby < <(tr -cd '0-9\n' < /tmp/apteka_counts.log | sed '/^$/d')
if [ "${#liczby[@]}" -ne 4 ]; then
  cat /tmp/apteka_counts.log
  echo 'Nie udało się odczytać liczby rekordów transakcyjnych.' >&2
  exit 1
fi

zaladuj_jesli_brakuje() {
  local indeks="$1" oczekiwane="$2" kontrolka="$3"
  if (( liczby[indeks] >= oczekiwane )); then
    echo "$kontrolka: komplet (${liczby[indeks]} rekordów)."
    return
  fi

  local log="/tmp/${kontrolka}_$$.log" bad="/tmp/${kontrolka}_$$.bad" rc=0
  echo "$kontrolka: ${liczby[indeks]}/$oczekiwane; uzupełniam z CSV."
  sqlldr "userid=${APP_USER}/${APP_USER_PASSWORD}@//localhost:1521/FREEPDB1" \
    "control=/scripts/import/${kontrolka}.ctl" \
    "log=$log" "bad=$bad" errors=1000000 rows=5000 bindsize=1048576 || rc=$?
  if (( rc > 2 )); then
    [ ! -f "$log" ] || cat "$log"
    return 1
  fi
  if (( rc == 2 )) && { [ ! -f "$log" ] || ! grep -q 'ORA-00001' "$log"; }; then
    [ ! -f "$log" ] || cat "$log"
    return 1
  fi
  if grep -E 'ORA-[0-9]+' "$log" | grep -v 'ORA-00001'; then
    cat "$log"
    return 1
  fi
  cat "$log"
}

zaladuj_jesli_brakuje 0 20000 zamowienie
zaladuj_jesli_brakuje 1 175000 pozycjazamowienia
zaladuj_jesli_brakuje 2 500000 sprzedaz
zaladuj_jesli_brakuje 3 1000000 pozycjasprzedazy

sqlplus -L -s / as sysdba <<'SQL'
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER TABLE APTEKA.ZAMOWIENIE MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);
ALTER TABLE APTEKA.POZYCJAZAMOWIENIA MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);
ALTER TABLE APTEKA.SPRZEDAZ MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);
ALTER TABLE APTEKA.POZYCJASPRZEDAZY MODIFY ID GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);
EXIT
SQL

stan_koncowy=$(sqlplus -L -s / as sysdba <<'SQL'
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;
SET PAGESIZE 0 FEEDBACK OFF VERIFY OFF HEADING OFF ECHO OFF
SELECT CASE WHEN
    (SELECT COUNT(*) FROM APTEKA.ZAMOWIENIE) >= 20000 AND
    (SELECT COUNT(*) FROM APTEKA.POZYCJAZAMOWIENIA) >= 175000 AND
    (SELECT COUNT(*) FROM APTEKA.SPRZEDAZ) >= 500000 AND
    (SELECT COUNT(*) FROM APTEKA.POZYCJASPRZEDAZY) >= 1000000
    THEN 'KOMPLET' ELSE 'BRAKI' END
FROM dual;
EXIT
SQL
)
stan_koncowy=$(printf '%s\n' "$stan_koncowy" | grep -Eo 'KOMPLET|BRAKI' | tail -n 1)
if [ "$stan_koncowy" != 'KOMPLET' ]; then
  echo 'Po loaderze nadal brakuje części danych transakcyjnych.' >&2
  exit 1
fi
echo 'Komplet danych transakcyjnych załadowany.'
